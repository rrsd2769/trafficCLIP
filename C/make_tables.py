"""Build results/comparison/master_table.csv from the per-experiment CSVs.

Every row is read from a results/comparison/*.csv file, except the
manuscript's own pre-fix Table 1 figures, which were never run here; those
are transcribed from the manuscript and flagged in the `source` column.
"""
import csv
from pathlib import Path

COMPARISON_DIR = Path(__file__).resolve().parent.parent / "results" / "comparison"
OUT_PATH = COMPARISON_DIR / "master_table.csv"

FIELDS = [
    "source", "model", "dataset", "variant", "n_seeds",
    "accuracy_mean", "accuracy_std", "macro_f1_mean", "macro_f1_std", "notes",
]

# The manuscript's own Table 1, transcribed. Not generated by this
# repository, so it is kept separate from the executed results.
B_MANUSCRIPT = [
    ("V1", 0.6274, 0.6221),
    ("V2", 0.6163, 0.5905),
    ("V3", 0.6163, 0.6310),
    ("V4", 0.7933, 0.7857),
    ("V5", 0.6644, 0.6701),
    ("Full", 0.8049, 0.7963),
]

# The manuscript's separate headline Macro-F1, reported outside Table 1 and
# reproduced by re-running its pre-fix evaluation path against a tuned Full
# checkpoint. No paired accuracy figure was given alongside it.
B_MANUSCRIPT_HEADLINE_F1 = 0.8754


def read_csv_rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def a_row(path, dataset, variant, notes="", model="TrafficCLIP (independent implementation)"):
    rows = read_csv_rows(COMPARISON_DIR / path)
    mean_row = next(r for r in rows if r["seed"] == "mean")
    std_row = next(r for r in rows if r["seed"] == "std")
    n_seeds = sum(1 for r in rows if r["seed"] not in ("mean", "std"))
    return {
        "source": "A (executed)",
        "model": model,
        "dataset": dataset,
        "variant": variant,
        "n_seeds": n_seeds,
        "accuracy_mean": mean_row["accuracy"],
        "accuracy_std": std_row["accuracy"],
        "macro_f1_mean": mean_row["macro_f1"],
        "macro_f1_std": std_row["macro_f1"],
        "notes": notes,
    }


def b_row(path, variant):
    """Multi-seed B_<variant>_seeds.csv row, as written by scripts/run_b_seeds.py."""
    rows = read_csv_rows(COMPARISON_DIR / path)
    accs = [float(r["accuracy"]) for r in rows]
    f1s = [float(r["macro_f1"]) for r in rows]
    n = len(rows)
    acc_mean = sum(accs) / n
    f1_mean = sum(f1s) / n
    acc_std = (sum((v - acc_mean) ** 2 for v in accs) / (n - 1)) ** 0.5
    f1_std = (sum((v - f1_mean) ** 2 for v in f1s) / (n - 1)) ** 0.5
    row = rows[0]
    return {
        "source": "B (executed, post-fix)",
        "model": row["model_version"],
        "dataset": "10class",
        "variant": variant,
        "n_seeds": n,
        "accuracy_mean": acc_mean,
        "accuracy_std": acc_std,
        "macro_f1_mean": f1_mean,
        "macro_f1_std": f1_std,
        "notes": f"seeds {sorted(int(r['seed']) for r in rows)}; use_stats_prompts={row['use_stats_prompts']}, use_stats={row['use_stats']}",
    }


def b_manuscript_rows():
    out = []
    for variant, acc, f1 in B_MANUSCRIPT:
        out.append({
            "source": "B (manuscript Table 1, pre-fix, not executed here)",
            "model": "optimized" if variant in ("V3", "V4", "V5", "Full") else "original",
            "dataset": "10class",
            "variant": variant,
            "n_seeds": "",
            "accuracy_mean": acc,
            "accuracy_std": "",
            "macro_f1_mean": f1,
            "macro_f1_std": "",
            "notes": "as reported in the manuscript's Table 1; not re-executed here",
        })
    out.append({
        "source": "B (manuscript headline, pre-fix, not executed here)",
        "model": "optimized",
        "dataset": "10class",
        "variant": "Full (headline)",
        "n_seeds": "",
        "accuracy_mean": "",
        "accuracy_std": "",
        "macro_f1_mean": B_MANUSCRIPT_HEADLINE_F1,
        "macro_f1_std": "",
        "notes": "the manuscript's separate headline figure, distinct from Table 1's Full row; traced to eval-time label leakage",
    })
    return out


def c_rows():
    rows = read_csv_rows(COMPARISON_DIR / "C_matrix.csv")
    out = []
    for r in rows:
        is_orig = r["dataset"].endswith("_orig")
        notes = (
            "trained on the model's own published input representation "
            "(scripts/extract_original_representations.py)"
            if is_orig else
            "trained on the 28x28 flow-byte image, not the model's own published input representation"
        )
        out.append({
            "source": "C (executed)",
            "model": r["model"],
            "dataset": r["dataset"],
            "variant": "default",
            "n_seeds": r["n_seeds"],
            "accuracy_mean": r["accuracy_mean"],
            "accuracy_std": r["accuracy_std"],
            "macro_f1_mean": r["macro_f1_mean"],
            "macro_f1_std": r["macro_f1_std"],
            "notes": notes,
        })
    return out


def main():
    out_rows = []
    out_rows.append(a_row("A_10class.csv", "10class", "main"))
    out_rows.append(a_row("A_20class.csv", "20class", "main"))
    out_rows.append(a_row("A_20class_brokenconv1.csv", "20class", "broken-conv1 ablation",
                          notes="conv1 left randomly initialised and frozen, as in src/models/traffic_clip.py"))

    a_full = "TrafficCLIP-Full (independent implementation of B's architecture)"
    out_rows.append(a_row("A_Full_10class.csv", "10class", "main", model=a_full))
    out_rows.append(a_row("A_Full_20class.csv", "20class", "main", model=a_full))
    out_rows.append(a_row("A_Full_20class_brokenconv1.csv", "20class", "broken-conv1 ablation",
                          notes="conv1 left randomly initialised and frozen", model=a_full))

    # Cross-dataset generalization (Phase 3): the same A/A-Full architectures, unmodified,
    # on three datasets never seen by USTC-TFC2016's own construction.
    out_rows.append(a_row("A_5class.csv", "iscxvpn_5class", "main",
                          notes="ISCXVPN2016, 5-class traffic-type taxonomy (Chat/Email/FileTransfer/P2P/VoIPVideo)"))
    out_rows.append(a_row("A_Full_5class.csv", "iscxvpn_5class", "main",
                          notes="ISCXVPN2016, 5-class traffic-type taxonomy", model=a_full))
    out_rows.append(a_row("A_5G_3class.csv", "5g_3class", "main",
                          notes="UFJF 5G Traffic Capture Dataset, 3-class (eMBB/URLLC/mMTC)"))
    out_rows.append(a_row("A_Full_5G_3class.csv", "5g_3class", "main",
                          notes="UFJF 5G Traffic Capture Dataset, 3-class", model=a_full))
    out_rows.append(a_row("A_IoT23_9class.csv", "iot23_9class", "main",
                          notes="IoT-23, 9-class (3 benign devices + 6 malware families)"))
    out_rows.append(a_row("A_Full_IoT23_9class.csv", "iot23_9class", "main",
                          notes="IoT-23, 9-class", model=a_full))

    out_rows.extend(b_manuscript_rows())
    for variant, fname in [("V1", "B_V1_seeds.csv"), ("V2", "B_V2_seeds.csv"), ("V3", "B_V3_seeds.csv"),
                           ("V4", "B_V4_seeds.csv"), ("V5", "B_V5_seeds.csv"), ("Full", "B_Full_seeds.csv")]:
        out_rows.append(b_row(fname, variant))
    out_rows.extend(c_rows())

    with open(OUT_PATH, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(out_rows)

    print(f"wrote {len(out_rows)} rows to {OUT_PATH}")


if __name__ == "__main__":
    main()
